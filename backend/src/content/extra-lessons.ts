import type { AsmTask, BugTask, CreTask, HeadTask, PathNode, PickTask, Task } from './types.js'

const pick = (
  title: string,
  ctx: string,
  options: string[],
  correct: number,
  okText: string,
  badText: string,
  answer: string,
  mono = false,
): PickTask => ({
  type: 'pick',
  title,
  ctx,
  options,
  correct,
  okText,
  badText,
  answer,
  ...(mono ? { mono: true } : {}),
})

const assemble = (
  title: string,
  ctx: string,
  file: string,
  blocks: Record<string, string>,
  pool: string[],
  right: string[],
  okText: string,
  badText: string,
  answer: string,
): AsmTask => ({
  type: 'asm',
  title,
  ctx,
  file,
  blocks,
  pool,
  right,
  okText,
  badText,
  answer,
})

const bug = (
  title: string,
  ctx: string,
  file: string,
  lang: BugTask['lang'],
  lines: string[],
  correct: number,
  okText: string,
  badText: string,
  answer: string,
): BugTask => ({
  type: 'bug',
  title,
  ctx,
  file,
  lang,
  lines,
  correct,
  okText,
  badText,
  answer,
})

const head = (
  title: string,
  ctx: string,
  site: { url: string; cta: string },
  options: string[],
  correct: number,
  okText: string,
  badText: string,
  answer: string,
): HeadTask => ({
  type: 'head',
  title,
  ctx,
  site,
  options,
  correct,
  okText,
  badText,
  answer,
})

const cre = (
  title: string,
  ctx: string,
  options: CreTask['options'],
  correct: number,
  okText: string,
  badText: string,
  answer: string,
): CreTask => ({
  type: 'cre',
  title,
  ctx,
  options,
  correct,
  okText,
  badText,
  answer,
})

const lesson = (id: string, name: string, tasks: Task[]): PathNode => ({
  id,
  kind: 'lesson',
  name,
  tasks,
})

