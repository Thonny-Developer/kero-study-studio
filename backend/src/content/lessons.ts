export const TRACKS: Track[] = ['code', 'mkt']

export interface FlatNode {
  track: Track
  unitIndex: number
  /** индекс внутри юнита — для зигзага на карте */
  indexInUnit: number
  /** сквозной индекс внутри трека — для разблокировки */
  order: number
  node: PathNode
  unit: Unit
}

const flat: Record<Track, FlatNode[]> = { code: [], mkt: [] }
for (const track of TRACKS) {
  let order = 0
  COURSE[track].forEach((unit, unitIndex) =>
    unit.nodes.forEach((node, indexInUnit) => flat[track].push({ track, unitIndex, indexInUnit, order: order++, node, unit })),
  )
}

export const trackNodes = (track: Track) => flat[track]

export function findNode(id: string): FlatNode | undefined {
  for (const track of TRACKS) {
    const hit = flat[track].find((f) => f.node.id === id)
    if (hit) return hit
  }
  return undefined
}

