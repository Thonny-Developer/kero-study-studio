// Подсказки «Блинк проверяет на лету»: подсвечивают, какие части промпта уже есть. Оценку ставит AI на сервере.
export const CRITERIA: { label: string; re: RegExp }[] = [
  { label: 'Роль', re: /(^|\s)ты\s*[—–-]|ты\s+[а-яё]+(ист|ер|ор|ик|лог)|представь/i },
  { label: 'Задача', re: /сделай|напиши|создай|придумай|сгенерируй|собери|составь/i },
  { label: 'Контекст', re: /для\s|аудитор|ца\b|клиент|студент|пользовател/i },
  { label: 'Формат', re: /формат|списк|html|таблиц|пункт|json|файл|\d+\s*(вариант|оффер|пункт|блок|иде)/i },
  { label: 'Ограничения', re: /не более|до \d+|максимум|без\s|только/i },
]

export function checkPrompt(text: string) {
  return CRITERIA.map((c) => ({ label: c.label, hit: c.re.test(text) }))
}
